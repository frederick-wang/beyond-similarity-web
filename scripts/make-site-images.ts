#!/usr/bin/env node
// Regenerates the site's derived images and writes them into the repository:
//
//   src/assets/share-en.png   the 1200×630 card that link previews show (og:image)
//   public/favicon-*.png      PNG favicons, sizes as listed in src/data/icons.ts
//   public/apple-touch-icon.png
//
// The card is HTML rendered by Playwright's Chromium with the site's own
// stylesheet, so it takes the page's palette, font stack and seal. Its words
// come from shareCardWords() in the facts module; the card records them as
// JSON in a "Card words" text chunk, which tests/metadata.spec.ts compares
// with the page head to catch a card left stale. Rendering uses the browser
// and the fonts of the machine that runs the script, so the card's Source
// chunk records the platform and the browser version it was rendered with.
//
// The PNG favicons are the seal artwork resized with sharp, cropped to the
// view box of the traced SVG favicon so that every icon frames the seal alike.
// That SVG comes from scripts/trace-seal.py; rerun it first when the seal
// changes.
//
// Each PNG carries its origin in tEXt chunks: `Source` and `Description`
// (registered PNG keywords) and `impeccable:prompt`, which the design tooling
// reads when it checks that every shipped raster records its provenance.
//
// Run it after changing the title, the authors, the seal or the palette, and
// commit the results.
//
// Usage: node scripts/make-site-images.ts

import { readFileSync, writeFileSync } from 'node:fs'
import { arch, release, type } from 'node:os'
import { chromium } from '@playwright/test'
import sharp, { type Sharp } from 'sharp'
import { appleTouchIcon, pngIcons, svgIcon } from '../src/data/icons.ts'
import { shareCardWords, type ShareCardWords } from '../src/data/paper.ts'
import { withTextChunks, type PngText } from './png.ts'

const root = new URL('../', import.meta.url)

interface Origin {
  /** How the image was made, opening the impeccable record. */
  readonly method: string
  readonly description: string
  readonly source: string
}

const shareCard = {
  output: 'src/assets/share-en.png',
  width: 1200,
  height: 630,
  method: 'Rendered from HTML, not generated by a model.',
  description:
    'Share card for link previews of the paper page: the scroll seal and the short title, the full paper title, the authors and the arXiv ID, on the white paper of the page.',
} as const

function escapeHtml(text: string): string {
  return text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;')
}

function shareCardHtml(words: ShareCardWords): string {
  const stylesheet = readFileSync(new URL('src/styles/global.css', root), 'utf8')
  const seal = readFileSync(new URL('src/assets/seal.png', root)).toString('base64')
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <style>${stylesheet}</style>
    <style>
      html,
      body {
        width: ${shareCard.width}px;
        height: ${shareCard.height}px;
        overflow: hidden;
      }

      .card {
        display: flex;
        flex-direction: column;
        height: 100%;
        padding: 60px 80px 58px;
        overflow: hidden;
      }

      .masthead {
        display: flex;
        align-items: center;
        gap: 18px;
        padding-bottom: 28px;
        border-bottom: 2px solid var(--rule);
      }

      .masthead img {
        display: block;
        width: 62px;
        height: 62px;
      }

      .masthead span {
        font-size: 36px;
        font-weight: 600;
        letter-spacing: 0.005em;
      }

      h1 {
        margin-top: 40px;
        font-size: 64px;
        font-weight: 650;
        line-height: 1.14;
        letter-spacing: -0.012em;
      }

      /* The byline sits at the foot; its top padding is the least room it
         leaves the title, so a title that grows into it overflows the card
         and the script stops. */
      .byline {
        display: flex;
        justify-content: space-between;
        gap: 40px;
        margin-top: auto;
        padding-top: 28px;
        font-size: 32px;
        color: var(--ink-muted);
      }
    </style>
  </head>
  <body>
    <main class="card">
      <header class="masthead">
        <img src="data:image/png;base64,${seal}" alt="" />
        <span>${escapeHtml(words.shortTitle)}</span>
      </header>
      <h1>${escapeHtml(words.title)}</h1>
      <footer class="byline">
        <span>${escapeHtml(words.authors.join(', '))}</span>
        <span>arXiv:${escapeHtml(words.arxivId)}</span>
      </footer>
    </main>
  </body>
</html>`
}

/** The rendered card, and the browser and platform that rendered it. */
async function renderShareCard(words: ShareCardWords): Promise<{ readonly png: Buffer; readonly renderer: string }> {
  const browser = await chromium.launch()
  try {
    const page = await browser.newPage({
      viewport: { width: shareCard.width, height: shareCard.height },
      deviceScaleFactor: 1,
      colorScheme: 'light',
    })
    await page.setContent(shareCardHtml(words))
    await page.evaluate(async () => {
      await document.fonts.ready
    })
    const overflow = await page.locator('.card').evaluate((card) => card.scrollHeight - card.clientHeight)
    if (overflow > 0) {
      throw new Error(`The share card text overflows the card by ${overflow}px; shorten the text or reduce the type size`)
    }
    return {
      png: await page.screenshot({ type: 'png' }),
      renderer: `Playwright Chromium ${browser.version()} on ${type()} ${release()} ${arch()}`,
    }
  } finally {
    await browser.close()
  }
}

/** The tEXt chunks recording an image's origin. */
function originTexts(origin: Origin): PngText[] {
  return [
    { keyword: 'Source', text: origin.source },
    { keyword: 'Description', text: origin.description },
    { keyword: 'impeccable:prompt', text: `${origin.method} ${origin.description} Source: ${origin.source}.` },
  ]
}

/** Writes the image as a PNG with these tEXt chunks right after its IHDR chunk. */
async function writePng(path: string, image: Sharp, texts: readonly PngText[]): Promise<void> {
  // Every PNG here is palette-quantised: an indexed palette of at most 256
  // colours (sharp's default) holds the antialiased text and the seal, and
  // effort 10 spends the most time on choosing it. sharp drops the renderer's
  // metadata, so the origin chunks are the only text left.
  const png = await image.png({ palette: true, compressionLevel: 9, effort: 10 }).toBuffer()
  writeFileSync(new URL(path, root), withTextChunks(png, texts))
  console.log(`wrote ${path}`)
}

/** The square of the seal artwork that every icon shows: the view box of the traced SVG favicon. */
function iconFrame(): { readonly left: number; readonly top: number; readonly side: number } {
  const svg = readFileSync(new URL(`public${svgIcon}`, root), 'utf8')
  const match = /viewBox="(\d+) (\d+) (\d+) (\d+)"/.exec(svg)
  if (match === null) {
    throw new Error(`public${svgIcon} has no view box in whole pixels; rerun scripts/trace-seal.py`)
  }
  const [, left, top, width, height] = match.map(Number)
  if (left === undefined || top === undefined || width === undefined || width !== height) {
    throw new Error(`public${svgIcon} must have a square view box`)
  }
  return { left, top, side: width }
}

/** A colour custom property as the light theme of the page's stylesheet defines it. */
function pageColour(property: string): string {
  const stylesheet = readFileSync(new URL('src/styles/global.css', root), 'utf8')
  // The light theme's :root block comes first; the dark theme redefines the property later.
  const colour = new RegExp(`${property}:\\s*(#[0-9a-f]{6});`, 'i').exec(stylesheet)?.[1]
  if (colour === undefined) {
    throw new Error(`src/styles/global.css defines no ${property} colour`)
  }
  return colour
}

async function writeIcons(): Promise<void> {
  const frame = iconFrame()
  const seal = sharp(readFileSync(new URL('src/assets/seal.png', root))).extract({
    left: frame.left,
    top: frame.top,
    width: frame.side,
    height: frame.side,
  })
  const method = 'Resized from the seal artwork, not generated by a model.'
  const source = `scripts/make-site-images.ts, src/assets/seal.png cropped to the view box of public${svgIcon} and resized with sharp`
  for (const icon of pngIcons) {
    await writePng(
      `public${icon.path}`,
      seal.clone().resize(icon.size, icon.size),
      originTexts({
        method,
        description: `Favicon, ${icon.size} px: the vermilion scroll seal of the paper page on a transparent background.`,
        source,
      }),
    )
  }
  // iOS rounds the corners of a home-screen icon; the margin keeps the seal clear of them.
  const margin = 22
  const paperColour = pageColour('--paper')
  await writePng(
    `public${appleTouchIcon.path}`,
    seal
      .clone()
      .resize(appleTouchIcon.size - 2 * margin, appleTouchIcon.size - 2 * margin)
      .extend({ top: margin, bottom: margin, left: margin, right: margin, background: paperColour })
      .flatten({ background: paperColour }),
    originTexts({
      method,
      description: `Apple touch icon, ${appleTouchIcon.size} px: the vermilion scroll seal of the paper page on the white paper of the page, with no transparency.`,
      source: `${source}, on the --paper colour of src/styles/global.css`,
    }),
  )
}

const words = shareCardWords()
const card = await renderShareCard(words)
await writePng(
  shareCard.output,
  sharp(card.png).removeAlpha(),
  originTexts({
    method: shareCard.method,
    description: shareCard.description,
    source: `scripts/make-site-images.ts, HTML rendered by ${card.renderer} from shareCardWords() in src/data/paper.ts, src/styles/global.css and src/assets/seal.png`,
  }).concat([{ keyword: 'Card words', text: JSON.stringify(words) }]),
)
await writeIcons()
